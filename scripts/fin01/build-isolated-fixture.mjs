import fs from 'node:fs';
const dir = 'docs/reports/fin01-r22/';
const tables = JSON.parse(fs.readFileSync(`${dir}fixture-tables.json`));
const functions = [...JSON.parse(fs.readFileSync(`${dir}fixture-functions.json`)), ...JSON.parse(fs.readFileSync(`${dir}fixture-final-dependencies.json`))];
const names = new Set(tables.map((table) => table.relname));
const excludedForeignKeys = [];
const quote = (value) => `"${value.replaceAll('"', '""')}"`;
const sql = [
  'begin;',
  '-- Synthetic fixture. Run only in the isolated loopback cluster; never Production.',
  "do $$ begin if not exists(select 1 from pg_roles where rolname='anon') then create role anon; create role authenticated; create role service_role; end if; end $$;",
  'create schema private; create schema extensions; create schema realtime;',
  'create extension pgcrypto with schema extensions;',
  "create type public.business_category as enum ('farmacia','abarrotes','verduleria/fruteria','antojitos','darkitchen','restaurante','food_service','apparel','hardware','otro');",
  'create sequence public.pos_change_seq; create sequence public.pos_sale_audit_events_id_seq;',
  'set check_function_bodies=off;',
  fs.readFileSync(`${dir}fixture-defaults.sql`, 'utf8'),
  // The sole external boundary double: Supabase Realtime transport. The real
  // broadcaster and financial/auth/entitlement functions execute unmodified.
  "create function realtime.send(jsonb,text,text,boolean) returns void language sql as $$ select; $$;"
];
for (const table of tables) {
  sql.push(`create table ${table.schema_name}.${table.relname} (${table.columns.map((column) => `${quote(column.name)} ${column.type}${column.generated ? ` generated always as (${column.default}) stored` : column.identity ? ' generated by default as identity' : column.default ? ` default ${column.default}` : ''}${column.not_null ? ' not null' : ''}`).join(',\n')});`);
}
for (const table of tables) {
  for (const constraint of table.constraints || []) {
    if (constraint.type === 'f') continue;
    sql.push(`alter table ${table.schema_name}.${table.relname} add constraint ${quote(constraint.name)} ${constraint.definition};`);
  }
}
for (const table of tables) {
  for (const constraint of table.constraints || []) {
    if (constraint.type !== 'f') continue;
    const target = constraint.definition.match(/REFERENCES (?:public\.)?([a-z0-9_]+)/)?.[1];
    if (!names.has(target)) { excludedForeignKeys.push({ table: table.relname, ...constraint }); continue; }
    sql.push(`alter table ${table.schema_name}.${table.relname} add constraint ${quote(constraint.name)} ${constraint.definition};`);
  }
  const constraintNames = new Set((table.constraints || []).map((c) => c.name));
  for (const index of table.indexes || []) {
    const name = index.match(/INDEX (\S+) ON/)?.[1];
    if (!constraintNames.has(name)) sql.push(`${index};`);
  }
  if (table.relrowsecurity) sql.push(`alter table ${table.schema_name}.${table.relname} enable row level security;`);
  sql.push(`revoke all on ${table.schema_name}.${table.relname} from public,anon,authenticated;`);
}
sql.push(...functions.map((fn) => `${fn.definition};`));
sql.push('grant usage on schema public,extensions to anon,authenticated;');
sql.push('revoke execute on all functions in schema private from public,anon,authenticated,service_role;');
sql.push('revoke execute on all functions in schema public from public,anon,authenticated;');
sql.push('commit;');
fs.writeFileSync(`${dir}isolated-schema.sql`, `${sql.join('\n\n')}\n`);
fs.writeFileSync(`${dir}fixture-boundaries.json`, JSON.stringify({ realtimeTransportDouble: true, functions: functions.length, tables: tables.length, excludedForeignKeys },null,2));
